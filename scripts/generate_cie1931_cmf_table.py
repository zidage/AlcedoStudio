"""Write the CIE 1931 2 degree colour matching functions as a C++ header (1 nm, 360 to 830 nm).

The film print reads them for rule 'as_shot_tint': the chromaticity and the luminance of a scene
light spectrum. The input is the CSV of CIE 018:2019 Table 6, the same input as
generate_planckian_locus_table.py.
"""

from __future__ import annotations

import argparse
import pathlib

from generate_planckian_locus_table import CIE_CMF_DATASET_DOI, load_cmf


def render_header(cmf: list[tuple[float, float, float, float]], source: str) -> str:
    first = int(cmf[0][0])
    for index, row in enumerate(cmf):
        if row[0] != float(first + index):
            raise RuntimeError(f"The CMF rows are not on a 1 nm grid at row {index}")
    lines = [
        "// Copyright 2026 Yurun Zi",
        "// SPDX-License-Identifier: GPL-3.0-only",
        "//",
        "// Generated by scripts/generate_cie1931_cmf_table.py.",
        "// Source CMF: CIE 1931 2 degree observer, 1 nm, CIE 018:2019 Table 6.",
        f"// Dataset DOI: {CIE_CMF_DATASET_DOI}",
        f"// Input: {source}",
        "",
        "#pragma once",
        "",
        "#include <array>",
        "",
        "namespace alcedo::cie1931 {",
        "",
        "/// The x, y, and z colour matching functions at one wavelength.",
        "struct CmfEntry {",
        "  double x_;",
        "  double y_;",
        "  double z_;",
        "};",
        "",
        f"inline constexpr double kFirstNm = {float(first):.1f};",
        "inline constexpr double kStepNm  = 1.0;",
        "",
        f"inline constexpr std::array<CmfEntry, {len(cmf)}> kCmf = {{{{",
    ]
    for _, x_bar, y_bar, z_bar in cmf:
        lines.append(f"    CmfEntry{{{x_bar:.12e}, {y_bar:.12e}, {z_bar:.12e}}},")
    lines.extend(["}};", "", "}  // namespace alcedo::cie1931", ""])
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate the CIE 1931 2 degree CMF table header.")
    parser.add_argument(
        "--output",
        type=pathlib.Path,
        default=pathlib.Path("alcedo_studio/src/include/edit/runtime/film/cie1931_cmf_table.hpp"),
    )
    parser.add_argument("--cie-cmf-csv", type=pathlib.Path)
    args = parser.parse_args()
    cmf, source = load_cmf(args.cie_cmf_csv)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(render_header(cmf, source), encoding="utf-8", newline="\n")
    print(f"Wrote {len(cmf)} CMF rows to {args.output}")


if __name__ == "__main__":
    main()
