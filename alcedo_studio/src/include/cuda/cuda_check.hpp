#pragma once

#include <stdexcept>
#include <string>

#include <cuda_runtime.h>

namespace alcedo::cuda {

inline void CheckCuda(cudaError_t status, const char* what) {
  if (status != cudaSuccess) {
    throw std::runtime_error(std::string(what) + ": " + cudaGetErrorString(status));
  }
}

}  // namespace alcedo::cuda
